use ts_rs::TS;
use uclip_core::*;

fn main() {
    let config = ts_rs::Config::default();
    let declarations = [
        Theme::decl(&config),
        SettingsSnapshot::decl(&config),
        UpdateSettings::decl(&config),
        ErrorCode::decl(&config),
        AppError::decl(&config),
        CapabilityState::decl(&config),
        PlatformCapability::decl(&config),
        PlatformReport::decl(&config),
        BootstrapSnapshot::decl(&config),
    ];
    let body = declarations
        .into_iter()
        .map(|declaration| format!("export {declaration}"))
        .collect::<Vec<_>>()
        .join("\n\n");
    let normalized = body
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n");
    println!(
        "// Generated by uclip-core/examples/export_contracts.rs. Do not edit.\n\n{normalized}"
    );
}
