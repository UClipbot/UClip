use ts_rs::TS;
use uclip_core::*;

fn main() {
    let config = ts_rs::Config::default();
    let declarations = [
        KeyChord::decl(&config),
        KeyBindings::decl(&config),
        KeyboardSnapshot::decl(&config),
        UpdateKeyBindings::decl(&config),
        DesktopPreferences::decl(&config),
        UpdateDesktopPreferences::decl(&config),
        DesktopStatus::decl(&config),
        QuickPastePreferences::decl(&config),
        UpdateQuickPastePreferences::decl(&config),
        QuickPasteSettings::decl(&config),
        QuickPasteItem::decl(&config),
        QuickPasteSnapshot::decl(&config),
        ChangeClipDeletion::decl(&config),
        ClipDeletionSnapshot::decl(&config),
        ChangeClipPin::decl(&config),
        ClipPinSnapshot::decl(&config),
        DeduplicatePinned::decl(&config),
        DeduplicationSnapshot::decl(&config),
        CollectionItem::decl(&config),
        CollectionsSnapshot::decl(&config),
        CreateCollection::decl(&config),
        RenameCollection::decl(&config),
        DeleteCollection::decl(&config),
        TransferMode::decl(&config),
        TransferClip::decl(&config),
        TransferClips::decl(&config),
        ClipTransferSnapshot::decl(&config),
        ClipTransferBatch::decl(&config),
        ClipKind::decl(&config),
        CapturePolicy::decl(&config),
        UpdateCapturePolicy::decl(&config),
        HistoryQuery::decl(&config),
        HistoryItem::decl(&config),
        HistoryPage::decl(&config),
        ClipDetail::decl(&config),
        ClipVersion::decl(&config),
        EditableContent::decl(&config),
        EditClip::decl(&config),
        PreviewAnchor::decl(&config),
        HoverPreviewRequest::decl(&config),
        ClipboardStatus::decl(&config),
        CopyResult::decl(&config),
        Theme::decl(&config),
        Language::decl(&config),
        SettingsSnapshot::decl(&config),
        UpdateSettings::decl(&config),
        SyncRole::decl(&config),
        SyncRemoteInput::decl(&config),
        SyncRemoteSettings::decl(&config),
        SyncStatus::decl(&config),
        UpdateSync::decl(&config),
        ErrorCode::decl(&config),
        AppError::decl(&config),
        CapabilityState::decl(&config),
        PlatformCapability::decl(&config),
        PlatformReport::decl(&config),
        BootstrapSnapshot::decl(&config),
    ];
    let body = declarations
        .into_iter()
        .map(|declaration| format!("export {declaration}"))
        .collect::<Vec<_>>()
        .join("\n\n");
    let normalized = body
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n");
    println!(
        "// Generated by uclip-core/examples/export_contracts.rs. Do not edit.\n\n{normalized}"
    );
}
