//! Informational attribution: explicit pasteboard metadata takes precedence over
//! the foreground app. AppKit has no public API identifying the pasteboard writer.
use super::buffer;
use objc2::rc::autoreleasepool;
use objc2_app_kit::{
    NSApplicationActivationPolicy, NSPasteboard, NSRunningApplication, NSWorkspace,
};
use objc2_foundation::NSString;

pub enum Source {
    Explicit(Option<String>),
    Foreground(Option<(i32, String)>),
}

impl Source {
    pub(super) fn capture() -> Self {
        autoreleasepool(|_| Self::from_board(&NSPasteboard::generalPasteboard()))
    }

    fn from_board(board: &NSPasteboard) -> Self {
        let Some(types) = board.types().filter(|types| types.len() <= 256) else {
            return Self::Explicit(None);
        };
        let has = |name| types.containsObject(&NSString::from_str(name));
        // Universal Clipboard and generated content must not inherit the
        // unrelated local foreground application's identity.
        if has("com.apple.is-remote-clipboard") || has("org.nspasteboard.AutoGeneratedType") {
            return Self::Explicit(None);
        }
        if has("org.nspasteboard.source") {
            let name = buffer(board, "org.nspasteboard.source", 256)
                .ok()
                .and_then(|bytes| String::from_utf8(bytes).ok())
                .and_then(|identifier| explicit_application(&identifier));
            // Empty/invalid explicit metadata means unknown, never foreground.
            return Self::Explicit(name);
        }
        Self::Foreground(foreground())
    }

    pub fn finish(self) -> Option<String> {
        match self {
            Self::Explicit(name) => name,
            Self::Foreground(before) => {
                autoreleasepool(|_| stable_foreground(before, foreground()))
            }
        }
    }
}

fn valid_name(name: String) -> Option<String> {
    let name = name.trim();
    (!name.is_empty() && name.len() <= 256 && !name.chars().any(char::is_control))
        .then(|| name.to_owned())
}

fn application_name(app: &NSRunningApplication) -> Option<String> {
    let name = app.localizedName()?;
    if name.len() > 256 {
        return None;
    }
    valid_name(name.to_string())
}

fn explicit_application(identifier: &str) -> Option<String> {
    // Source markers contain a bundle identifier, not a path, title or URL.
    if identifier.is_empty()
        || identifier.len() > 256
        || !identifier.contains('.')
        || !identifier
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'.' | b'-'))
    {
        return None;
    }
    let apps = NSRunningApplication::runningApplicationsWithBundleIdentifier(&NSString::from_str(
        identifier,
    ));
    apps.firstObject()
        .and_then(|app| application_name(&app))
        .or_else(|| Some(identifier.to_owned()))
}

fn foreground() -> Option<(i32, String)> {
    let app = NSWorkspace::sharedWorkspace().frontmostApplication()?;
    let pid = app.processIdentifier();
    let bundle = app
        .bundleIdentifier()
        .filter(|value| value.len() <= 256)
        .map(|value| value.to_string());
    if !eligible_foreground(
        pid,
        app.isTerminated(),
        app.activationPolicy(),
        bundle.as_deref(),
    ) {
        return None;
    }
    Some((pid, application_name(&app)?))
}

fn eligible_foreground(
    pid: i32,
    terminated: bool,
    policy: NSApplicationActivationPolicy,
    bundle: Option<&str>,
) -> bool {
    // Accessory applications can own real, copy-capable windows (for example a
    // terminal configured to hide its Dock icon). Leave prohibited agents and
    // known transient system panels unknown instead of attributing their foreground.
    pid > 0
        && pid as u32 != std::process::id()
        && !terminated
        && matches!(
            policy,
            NSApplicationActivationPolicy::Regular | NSApplicationActivationPolicy::Accessory
        )
        && !matches!(
            bundle,
            Some(
                "com.apple.UserNotificationCenter"
                    | "com.apple.notificationcenterui"
                    | "com.apple.controlcenter"
                    | "com.apple.systemuiserver"
            )
        )
}

fn stable_foreground(
    before: Option<(i32, String)>,
    after: Option<(i32, String)>,
) -> Option<String> {
    let (before_pid, name) = before?;
    let (after_pid, _) = after?;
    (before_pid == after_pid).then_some(name)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn accessory_apps_are_valid_sources_but_self_and_system_panels_are_not() {
        use NSApplicationActivationPolicy as Policy;
        assert!(eligible_foreground(
            42,
            false,
            Policy::Regular,
            Some("com.google.Chrome")
        ));
        assert!(eligible_foreground(
            42,
            false,
            Policy::Accessory,
            Some("org.tabby")
        ));
        assert!(eligible_foreground(
            42,
            false,
            Policy::Accessory,
            Some("com.example.MenuBarEditor")
        ));
        assert!(!eligible_foreground(
            42,
            false,
            Policy::Prohibited,
            Some("com.example.Agent")
        ));
        assert!(!eligible_foreground(
            42,
            true,
            Policy::Regular,
            Some("com.google.Chrome")
        ));
        assert!(!eligible_foreground(
            std::process::id() as i32,
            false,
            Policy::Regular,
            Some("app.uclip.dev")
        ));
        for bundle in [
            "com.apple.UserNotificationCenter",
            "com.apple.notificationcenterui",
            "com.apple.controlcenter",
            "com.apple.systemuiserver",
        ] {
            assert!(!eligible_foreground(
                42,
                false,
                Policy::Accessory,
                Some(bundle)
            ));
        }
    }

    #[test]
    fn native_pasteboard_markers_override_foreground_and_preserve_unknown() {
        autoreleasepool(|_| {
            // A private pasteboard exercises AppKit without replacing the user's clipboard.
            let board = NSPasteboard::pasteboardWithUniqueName();
            let source = NSString::from_str("org.nspasteboard.source");
            for identifier in [
                "com.apple.TextEdit",
                "",
                "invalid\nsource",
                &"x".repeat(257),
            ] {
                board.clearContents();
                assert!(board.setString_forType(&NSString::from_str(identifier), &source));
                let snapshot = Source::from_board(&board);
                assert!(matches!(snapshot, Source::Explicit(_)));
                let name = snapshot.finish();
                if identifier == "com.apple.TextEdit" {
                    assert!(name.is_some());
                } else {
                    assert_eq!(name, None);
                }
            }
            for flag in [
                "com.apple.is-remote-clipboard",
                "org.nspasteboard.AutoGeneratedType",
            ] {
                board.clearContents();
                assert!(board.setString_forType(&NSString::from_str("com.apple.TextEdit"), &source));
                assert!(
                    board.setString_forType(&NSString::from_str("1"), &NSString::from_str(flag))
                );
                assert_eq!(Source::from_board(&board).finish(), None);
            }
            // SAFETY: public NSPasteboard selector with no arguments or return value;
            // objc2-app-kit does not expose this oneway method. Board is private.
            let _: () = unsafe { objc2::msg_send![&*board, releaseGlobally] };
        });
    }

    #[test]
    fn changing_or_missing_foreground_does_not_misattribute_a_copy() {
        let app = || Some((42, "TextEdit".into()));
        assert_eq!(stable_foreground(app(), app()).as_deref(), Some("TextEdit"));
        assert_eq!(stable_foreground(app(), Some((43, "Safari".into()))), None);
        assert_eq!(stable_foreground(app(), None), None);
        assert_eq!(stable_foreground(None, app()), None);
        assert_eq!(Source::Explicit(None).finish(), None);
        assert_eq!(
            Source::Explicit(Some("Safari".into())).finish().as_deref(),
            Some("Safari")
        );
    }

    #[test]
    fn source_metadata_is_bounded_and_invalid_markers_do_not_become_names() {
        for invalid in [
            "",
            "Safari",
            "file:///Applications/Safari.app",
            "com.apple.Safari\n",
            "com.apple.\0Safari",
        ] {
            assert_eq!(explicit_application(invalid), None);
        }
        assert_eq!(valid_name(" Safari ".into()).as_deref(), Some("Safari"));
        assert_eq!(
            valid_name("\u{6587}\u{672c}\u{7f16}\u{8f91}".into()).as_deref(),
            Some("\u{6587}\u{672c}\u{7f16}\u{8f91}")
        );
        for invalid in ["".into(), "x".repeat(257), "Safari\nsecret".into()] {
            assert_eq!(valid_name(invalid), None);
        }
    }
}
